import { Command } from 'commander'
import { tildify } from '../core/config.js'
import { emitJson, getOutputContext, info, log, success } from '../core/output.js'
import { detectShell, shellIntegrationStatus, type Shell } from '../core/shell-rc.js'
import {
  installSkills,
  listBundledSkillNames,
  reportInstall,
  targetsWithSkills,
} from './skills.js'

/**
 * Bring what grove installed outside itself up to this version, without
 * asking the questions a first install does. Only places that already have
 * grove's skills are touched, and edited skills are left alone.
 */
export function updateCommand(): Command {
  return new Command('update')
    .description("Update grove's agent skills to this version and check the shell integration")
    .action(async () => {
      const targets = targetsWithSkills(await listBundledSkillNames())
      const skills = await installSkills(targets)
      const shell = await shellStatus()

      if (getOutputContext().json) {
        emitJson({ ok: true, skills, shell })
        return
      }

      log()
      if (targets.length === 0) {
        info('No grove skills installed. Run `grove skills install` to add them.')
      } else {
        reportInstall(skills)
        if (skills.some((report) => report.installed.length + report.updated.length > 0)) {
          info('Agents will pick these up on their next session.')
        }
      }

      if (shell.installedIn) {
        success(
          `Shell integration loads from ${tildify(shell.installedIn)} and is regenerated by each new shell`,
        )
        info('Open a new terminal to use this version in it.')
      } else {
        info(`No shell integration for ${shell.shell}. Run \`grove shell-init --install\` to add it.`)
      }
      log()
    })
}

async function shellStatus(): Promise<{ shell: Shell; installedIn: string | null }> {
  const shell = detectShell()
  const status = await shellIntegrationStatus(shell)
  return { shell, installedIn: status.installedIn ?? null }
}
